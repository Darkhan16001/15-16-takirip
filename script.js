  const STORAGE_KEY =
    "darkhan-history-15-16-complete";

  let awarded = [{}, {}, {}];

  try {
    const stored = JSON.parse(
      localStorage.getItem(STORAGE_KEY)
    );

    if (
      Array.isArray(stored) &&
      stored.length === 3 &&
      stored.every(item =>
        item &&
        typeof item === "object" &&
        !Array.isArray(item)
      )
    ) {
      awarded = stored;
    }
  } catch (error) {
    awarded = [{}, {}, {}];
  }

  function saveScores() {
    try {
      localStorage.setItem(
        STORAGE_KEY,
        JSON.stringify(awarded)
      );
    } catch (error) {
      // Сақтау өшірілсе де,
      // ұпай санау жалғасады.
    }
  }

  function teamScore(team) {
    return Object.values(
      awarded[team]
    ).reduce(
      (sum, points) =>
        sum + (Number(points) || 0),
      0
    );
  }

