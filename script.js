  document.addEventListener("click", event => {
    const button = event.target.closest("button");

    if (!button) return;

    // Таймер

    if (button.id === "startTimer") {
      startTimer();
      return;
    }

    if (button.id === "pauseTimer") {
      pauseTimer();
      return;
    }

    if (button.id === "resetTimer") {
      resetTimer();
      return;
    }

    // Беттер арасында ауысу

    if (button.id === "previous") {
      showPage(page - 1);
      return;
    }

    if (button.id === "next") {
      showPage(page + 1);
      return;
    }

    // Оң жақтағы кезеңдер

    if (button.hasAttribute("data-stage")) {
      showPage(Number(button.dataset.stage));
      return;
    }

    // Сұрақ жауабын ашу

    if (button.hasAttribute("data-reveal")) {
      const answer = $(
        button.dataset.reveal
      );

      if (!answer) return;

      answer.classList.toggle("open");

      button.textContent =
        answer.classList.contains("open")
          ? "Жауапты жасыру"
          : "Жауабын көрсету";

      return;
    }

    // Командаға ұпай беру

    if (button.hasAttribute("data-points")) {
      toggleScore(button);
      return;
    }

    // Ұпайларды нөлдеу

    if (button.id === "resetScores") {
      resetScores();
      return;
    }

    // Студентті кездейсоқ таңдау

    if (button.id === "pickStudent") {
      pickStudent();
      return;
    }

    // Бірінші немесе екінші видео

    if (button.hasAttribute("data-video")) {
      currentVideo = Number(
        button.dataset.video
      );

      videoMode = "youtube";
      renderVideo();
      return;
    }

    // Балама түсіндірме

    if (button.dataset.videoMode === "slides") {
      videoMode = "slides";
      slideIndex = 0;
      renderVideo();
      return;
    }

    // Интерактивті көрініс ауыстыру

    if (button.hasAttribute("data-slide")) {
      const direction = Number(
        button.dataset.slide
      );

      slideIndex = (
        slideIndex + direction + slides.length
      ) % slides.length;

      renderVideo();
      return;
    }
  });

