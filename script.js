  function pickStudent() {
    const input = $("studentNames");
    const result = $("studentResult");

    if (!input || !result) return;

    const names = [
      ...new Set(
        input.value
          .split(/[,;\n]+/)
          .map(name => name.trim())
          .filter(Boolean)
      )
    ];

    if (!names.length) {
      result.textContent =
        "Алдымен студенттердің есімдерін жазыңдар.";
      return;
    }

    if (!studentPool.length) {
      studentPool = [...names];
    }

    const randomIndex = Math.floor(
      Math.random() * studentPool.length
    );

    const selected = studentPool.splice(
      randomIndex,
      1
    )[0];

    result.textContent =
      "Таңдалған студент: " + selected;
  }

