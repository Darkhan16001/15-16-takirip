  const TOTAL_MS = 80 * 60 * 1000;

  let savedElapsed = 0;
  let startMoment = null;
  let interval = null;

  function getElapsed() {
    return startMoment === null
      ? savedElapsed
      : savedElapsed + Date.now() - startMoment;
  }

  function formatTime(ms) {
    const seconds = Math.floor(ms / 1000);
    const minutes = Math.floor(seconds / 60);

    return (
      String(minutes).padStart(2, "0") +
      ":" +
      String(seconds % 60).padStart(2, "0")
    );
  }

  function updateTimer() {
    const elapsed = Math.min(
      getElapsed(),
      TOTAL_MS
    );

    const remaining = Math.max(
      TOTAL_MS - elapsed,
      0
    );

    $("timer").textContent = formatTime(elapsed);

    $("remaining").textContent =
      remaining > 0
        ? "Қалғаны: " + formatTime(remaining)
        : "80 минут аяқталды";

    if (remaining === 0 && startMoment !== null) {
      pauseTimer();
    }
  }

  function startTimer() {
    if (startMoment !== null) return;

    if (savedElapsed >= TOTAL_MS) {
      savedElapsed = 0;
    }

    startMoment = Date.now();

    interval = setInterval(
      updateTimer,
      500
    );

    updateTimer();
  }

  function pauseTimer() {
    if (startMoment === null) return;

    savedElapsed = Math.min(
      getElapsed(),
      TOTAL_MS
    );

    startMoment = null;

    clearInterval(interval);
    interval = null;

    updateTimer();
  }

  function resetTimer() {
    pauseTimer();
    savedElapsed = 0;
    updateTimer();
  }

